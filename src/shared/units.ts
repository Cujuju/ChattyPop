// Unit conversions shared by every process, so no file restates them.
export const MS_PER_S = 1000;
export const MS_PER_MIN = 60 * MS_PER_S;
export const MS_PER_HOUR = 60 * MS_PER_MIN;
export const MS_PER_DAY = 24 * MS_PER_HOUR;

export const BYTES_PER_KB = 1024;
export const BYTES_PER_MB = 1024 * BYTES_PER_KB;
export const BYTES_PER_GB = 1024 * BYTES_PER_MB;
